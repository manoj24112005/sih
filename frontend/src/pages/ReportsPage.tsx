import React, { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import {
  FileSpreadsheet,
  Download,
  RefreshCw,
  ExternalLink,
  ShieldCheck,
  CheckCircle2,
  Calendar,
  FileCheck2
} from "lucide-react";
import { api } from "../services/api";
import { ReportRecord } from "../types";
import { Badge } from "../components/ui/Badge";

export const ReportsPage: React.FC = () => {
  const [reports, setReports] = useState<ReportRecord[]>([]);
  const [loading, setLoading] = useState<boolean>(true);

  const fetchReports = async () => {
    try {
      setLoading(true);
      const res = await api.getReports();
      setReports(res);
    } catch (err) {
      console.error("Failed to load reports:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchReports();
  }, []);

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 border-b border-slate-200 pb-5">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900">
            Compliance Assessment Reports
          </h1>
          <p className="text-xs text-slate-500 mt-1">
            Downloadable official audit dossiers generated by the ReportLab engine, compiling evidence, findings, and recommendations.
          </p>
        </div>

        <button
          onClick={fetchReports}
          className="p-2 border border-slate-300 rounded-md bg-white hover:bg-slate-50 text-slate-600 transition-colors self-start sm:self-auto"
          title="Refresh list"
        >
          <RefreshCw className={`w-4 h-4 ${loading ? "animate-spin" : ""}`} />
        </button>
      </div>

      {/* Reports Table */}
      <div className="bg-white rounded-lg border border-slate-200 shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs divide-y divide-slate-200">
            <thead className="bg-slate-50 text-slate-700 font-semibold uppercase tracking-wider text-[11px]">
              <tr>
                <th className="px-4 py-3">Report Identifier</th>
                <th className="px-4 py-3">Institution Name</th>
                <th className="px-4 py-3">Application Case</th>
                <th className="px-4 py-3">Generated Date</th>
                <th className="px-4 py-3">Signatory Assessor</th>
                <th className="px-4 py-3">File Size</th>
                <th className="px-4 py-3 text-right">Download Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200 bg-white">
              {loading ? (
                <tr>
                  <td colSpan={7} className="px-4 py-8 text-center text-slate-400">
                    <RefreshCw className="w-5 h-5 text-teal-600 animate-spin mx-auto mb-2" />
                    Loading generated reports...
                  </td>
                </tr>
              ) : reports.length === 0 ? (
                <tr>
                  <td colSpan={7} className="px-4 py-12 text-center text-slate-400">
                    <FileSpreadsheet className="w-10 h-10 text-slate-300 mx-auto mb-2" />
                    <p className="font-semibold text-slate-700">No reports generated yet</p>
                    <p className="text-[11px] text-slate-400 mt-0.5 max-w-sm mx-auto">
                      Open an application case from the Applications workspace and click "Generate PDF Report" to export a formal compliance audit dossier.
                    </p>
                    <Link
                      to="/applications"
                      className="mt-3 inline-block px-3 py-1.5 bg-slate-900 text-white rounded text-xs font-medium hover:bg-slate-800"
                    >
                      Go to Applications
                    </Link>
                  </td>
                </tr>
              ) : (
                reports.map((rep) => (
                  <tr key={rep.id} className="hover:bg-slate-50 transition-colors">
                    <td className="px-4 py-3.5 font-mono font-bold text-teal-700 whitespace-nowrap">
                      {rep.report_identifier}
                    </td>
                    <td className="px-4 py-3.5 font-semibold text-slate-900">
                      {rep.institution_name || "Institution Dossier"}
                    </td>
                    <td className="px-4 py-3.5 font-mono text-slate-600 whitespace-nowrap">
                      <Link
                        to={`/applications/${rep.application_id}`}
                        className="hover:text-teal-700 hover:underline"
                      >
                        {rep.application_number || `Case #${rep.application_id}`}
                      </Link>
                    </td>
                    <td className="px-4 py-3.5 font-mono text-slate-500 whitespace-nowrap">
                      {new Date(rep.created_at).toLocaleString([], {
                        dateStyle: "medium",
                        timeStyle: "short"
                      })}
                    </td>
                    <td className="px-4 py-3.5 text-slate-700 whitespace-nowrap">
                      {rep.generated_by}
                    </td>
                    <td className="px-4 py-3.5 font-mono text-slate-500 whitespace-nowrap">
                      {(rep.file_size / 1024).toFixed(1)} KB
                    </td>
                    <td className="px-4 py-3.5 text-right whitespace-nowrap">
                      <a
                        href={api.getReportDownloadUrl(rep.id)}
                        target="_blank"
                        rel="noopener noreferrer"
                        download={`${rep.report_identifier}.pdf`}
                        className="inline-flex items-center gap-1.5 px-3 py-1.5 bg-slate-900 hover:bg-slate-800 text-white rounded text-xs font-medium transition-colors shadow-xs"
                      >
                        <Download className="w-3.5 h-3.5 text-teal-400" />
                        <span>Download PDF</span>
                      </a>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
